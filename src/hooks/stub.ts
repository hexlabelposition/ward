import type { HookName } from "./list.ts";

/** Bump when the stub format changes, so `ward run` / install can rewrite old stubs. */
export const STUB_VERSION = 1;

/** Suffix of a foreign hook that was moved aside on install and now runs before ward. */
export const CHAINED_SUFFIX = ".pre-ward";

const MARKER = "# ward:managed";
const MARKER_RE = /^# ward:managed v(\d+)$/m;

/** Hooks that read data from stdin, which both the chained hook and ward need. */
const STDIN_HOOKS: ReadonlySet<HookName> = new Set([
  "pre-push",
  "post-rewrite",
]);

export type StubOptions = {
  /**
   * Path to the ward binary, relative to the repo root (git runs hooks from the
   * root of the working tree). Default: `node_modules/.bin/ward`.
   */
  bin?: string;
};

/**
 * Shell stub for one hook. It holds no logic: it only hands off to `ward run`.
 *
 * - A hook that was there before ward (`<hook>.pre-ward`) runs first; if it
 *   fails, git stops and ward does not run.
 * - If the binary is missing (dependencies not installed yet), it warns and
 *   lets git continue instead of blocking every commit.
 */
export function renderStub(
  hook: HookName,
  { bin = "node_modules/.bin/ward" }: StubOptions = {},
): string {
  const chain = STDIN_HOOKS.has(hook)
    ? // stdin can be read once: keep a copy for both hooks.
      `if [ -x "$prev" ]; then
  input="$(mktemp)" || exit 1
  trap 'rm -f "$input"' EXIT
  cat > "$input"
  "$prev" "$@" < "$input" || exit $?
  ward "$@" < "$input"
  exit $?
fi
`
    : `if [ -x "$prev" ]; then
  "$prev" "$@" || exit $?
fi
`;

  return `#!/bin/sh
${MARKER} v${String(STUB_VERSION)}
# Generated by ward, do not edit: changes are overwritten on install.
bin=${shQuote(bin)}
prev="$0${CHAINED_SUFFIX}"
ward() {
  if [ ! -f "$bin" ]; then
    echo "ward: $bin not found, skipping ${hook} (install dependencies to enable hooks)" >&2
    return 0
  fi
  "$bin" run ${hook} "$@"
}
${chain}ward "$@"
`;
}

/** Stub version from the marker, or `null` if the file was not written by ward. */
export function getStubVersion(content: string): number | null {
  const match = MARKER_RE.exec(content);
  return match?.[1] === undefined ? null : Number(match[1]);
}

export function isManagedStub(content: string): boolean {
  return getStubVersion(content) !== null;
}

function shQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}
