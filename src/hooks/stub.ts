import type { Runtime } from "../runtime/detect.ts";
import type { HookName } from "./list.ts";

/** Bump when the stub format changes, so `ward run` / install can rewrite old stubs. */
export const STUB_VERSION = 2;

/** What a Deno stub runs: Deno resolves the version from deno.json / package.json and its lockfile. */
const DENO_SPECIFIER = "npm:@hexlabelposition/ward";

/** Suffix of a foreign hook that was moved aside on install and now runs before ward. */
export const CHAINED_SUFFIX = ".pre-ward";

const MARKER = "# ward:managed";
const MARKER_RE = /^# ward:managed v(\d+)$/m;

/** Hooks that read data from stdin, which both the chained hook and ward need. */
const STDIN_HOOKS: ReadonlySet<HookName> = new Set([
  "pre-push",
  "post-rewrite",
]);

export type StubOptions = {
  /**
   * Path to the ward binary, relative to the repo root (git runs hooks from the
   * root of the working tree). Default: `node_modules/.bin/ward`.
   */
  bin?: string;
  /**
   * Runtime the stub starts ward with, unless `WARD_RUNTIME` says otherwise at
   * run time. Install passes the runtime it runs on. Default: `node`.
   */
  runtime?: Runtime;
};

/**
 * Shell stub for one hook. It holds no logic: it only hands off to `ward run`.
 *
 * - A hook that was there before ward (`<hook>.pre-ward`) runs first; if it
 *   fails, git stops and ward does not run.
 * - `WARD=0` skips ward without starting it. A chained hook still runs: it
 *   is not ward's (git-lfs), and `--no-verify` is there to skip everything.
 * - If the binary is missing (dependencies not installed yet), it warns and
 *   lets git continue instead of blocking every commit.
 * - `WARD_RUNTIME` (`node` / `bun` / `deno`) picks the runtime, so a stub
 *   written on one runtime can run on another. On Node the binary runs
 *   through its shebang; Bun is started explicitly, since the shebang names
 *   `node`, which may not be installed. Deno has no `node_modules/.bin` by
 *   default, so it runs `npm:@hexlabelposition/ward` instead of the binary.
 *   An unknown value or a missing runtime fails the hook: it was asked for,
 *   so skipping would hide it.
 */
export function renderStub(
  hook: HookName,
  { bin = "node_modules/.bin/ward", runtime = "node" }: StubOptions = {},
): string {
  const chain = STDIN_HOOKS.has(hook)
    ? // stdin can be read once: keep a copy for both hooks.
      `if [ -x "$prev" ]; then
  input="$(mktemp)" || exit 1
  trap 'rm -f "$input"' EXIT
  cat > "$input"
  "$prev" "$@" < "$input" || exit $?
  ward "$@" < "$input"
  exit $?
fi
`
    : `if [ -x "$prev" ]; then
  "$prev" "$@" || exit $?
fi
`;

  return `#!/bin/sh
${MARKER} v${String(STUB_VERSION)}
# Generated by ward, do not edit: changes are overwritten on install.
bin=${shQuote(bin)}
prev="$0${CHAINED_SUFFIX}"
found() {
  command -v "$1" >/dev/null 2>&1 && return 0
  echo "ward: $1 not found in PATH, can't run ${hook} (use WARD_RUNTIME=node, or WARD=0 to skip)" >&2
  return 1
}
ward() {
  [ "\${WARD-}" = "0" ] && return 0
  runtime="\${WARD_RUNTIME:-${runtime}}"
  case "$runtime" in
    node | bun | deno) ;;
    *)
      echo "ward: unknown WARD_RUNTIME=\\"$runtime\\", expected node, bun or deno" >&2
      return 1 ;;
  esac
  if [ "$runtime" = deno ]; then
    found deno || return 1
    deno run -A ${DENO_SPECIFIER} run ${hook} "$@"
    return
  fi
  if [ ! -f "$bin" ]; then
    echo "ward: $bin not found, skipping ${hook} (install dependencies to enable hooks)" >&2
    return 0
  fi
  if [ "$runtime" = bun ]; then
    found bun || return 1
    bun "$bin" run ${hook} "$@"
  else
    "$bin" run ${hook} "$@"
  fi
}
${chain}ward "$@"
`;
}

/** Stub version from the marker, or `null` if the file was not written by ward. */
export function getStubVersion(content: string): number | null {
  const match = MARKER_RE.exec(content);
  return match?.[1] === undefined ? null : Number(match[1]);
}

/**
 * The options a ward stub was written with, read back from it, so a stale
 * stub can be rewritten as install wrote it. `null` when the `bin` line is
 * not there. Stubs before v2 have no runtime line: they always ran Node.
 */
export function readStubOptions(content: string): Required<StubOptions> | null {
  const bin = /^bin='((?:[^']|'\\'')*)'$/m.exec(content)?.[1];
  if (bin === undefined) return null;
  const runtime =
    /^\s*runtime="\$\{WARD_RUNTIME:-(node|bun|deno)\}"$/m.exec(content)?.[1] ??
    "node";
  return { bin: bin.replaceAll(`'\\''`, "'"), runtime: runtime as Runtime };
}

export function isManagedStub(content: string): boolean {
  return getStubVersion(content) !== null;
}

function shQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}
