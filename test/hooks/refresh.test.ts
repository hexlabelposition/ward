import {
  chmodSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { installHooks, refreshHooks } from "../../src/hooks/install.ts";
import { HOOKS } from "../../src/hooks/list.ts";
import { refreshStaleStubs } from "../../src/hooks/refresh.ts";
import { renderStub, STUB_VERSION } from "../../src/hooks/stub.ts";
import { createTempRepo, type TempRepo } from "../helpers/git-repo.ts";

const posixOnly = process.platform === "win32" ? it.skip : it;

/** A stub as Ward 0.1 / 0.2 wrote it. */
function v1Stub(hook: string, bin = "node_modules/.bin/ward"): string {
  return `#!/bin/sh
# ward:managed v1
# Generated by ward, do not edit: changes are overwritten on install.
bin='${bin}'
prev="$0.pre-ward"
ward() {
  [ "\${WARD-}" = "0" ] && return 0
  if [ ! -f "$bin" ]; then
    echo "ward: $bin not found, skipping ${hook} (install dependencies to enable hooks)" >&2
    return 0
  fi
  "$bin" run ${hook} "$@"
}
if [ -x "$prev" ]; then
  "$prev" "$@" || exit $?
fi
ward "$@"
`;
}

/** A repo with v1 stubs for every hook, using `dist/cli.mjs`. */
function setup() {
  const repo = createTempRepo();
  for (const hook of HOOKS) {
    writeFileSync(join(hooksDirOf(repo), hook), v1Stub(hook, "dist/cli.mjs"));
  }
  return repo;
}

function hooksDirOf(repo: TempRepo): string {
  return join(repo.dir, ".git", "hooks");
}

const read = (hooksDir: string, hook: string) =>
  readFileSync(join(hooksDir, hook), "utf8");

describe("refreshStaleStubs", () => {
  it("rewrites stubs of another version with their bin and runtime", async () => {
    using repo = setup();
    const hooksDir = hooksDirOf(repo);

    expect(await refreshStaleStubs(hooksDir, "pre-commit")).toEqual([...HOOKS]);
    for (const hook of HOOKS) {
      expect(read(hooksDir, hook)).toBe(
        renderStub(hook, { bin: "dist/cli.mjs", runtime: "node" }),
      );
    }
  });

  it("rewrites a newer stub too", async () => {
    using repo = createTempRepo();
    const hooksDir = join(repo.dir, ".git", "hooks");
    installHooks(hooksDir, { runtime: "bun" });
    const newer = renderStub("pre-push", { runtime: "bun" }).replace(
      `# ward:managed v${String(STUB_VERSION)}`,
      `# ward:managed v${String(STUB_VERSION + 1)}`,
    );
    writeFileSync(join(hooksDir, "pre-push"), newer);

    expect(await refreshStaleStubs(hooksDir, "pre-push")).toEqual(["pre-push"]);
    expect(read(hooksDir, "pre-push")).toBe(
      renderStub("pre-push", { runtime: "bun" }),
    );
  });

  it("does nothing when the stub is current", async () => {
    using repo = createTempRepo();
    const hooksDir = join(repo.dir, ".git", "hooks");
    installHooks(hooksDir);
    // Only the calling stub is checked, to keep the no-op path cheap.
    writeFileSync(join(hooksDir, "pre-push"), v1Stub("pre-push"));

    expect(await refreshStaleStubs(hooksDir, "pre-commit")).toEqual([]);
    expect(read(hooksDir, "pre-push")).toBe(v1Stub("pre-push"));
  });

  it.each([
    ["no stub", null],
    ["a foreign hook", "#!/bin/sh\nnpx lint-staged\n"],
    ["a stub without the bin line", "#!/bin/sh\n# ward:managed v1\n"],
  ])("does nothing for %s", async (_, content) => {
    using repo = createTempRepo();
    const hooksDir = join(repo.dir, ".git", "hooks");
    rmSync(join(hooksDir, "pre-commit"), { force: true });
    if (content !== null) writeFileSync(join(hooksDir, "pre-commit"), content);
    writeFileSync(join(hooksDir, "pre-push"), v1Stub("pre-push"));

    expect(await refreshStaleStubs(hooksDir, "pre-commit")).toEqual([]);
    expect(read(hooksDir, "pre-push")).toBe(v1Stub("pre-push"));
  });

  it("does nothing when the hook path is a directory", async () => {
    using repo = createTempRepo();
    const hooksDir = join(repo.dir, ".git", "hooks");
    mkdirSync(join(hooksDir, "pre-commit"), { recursive: true });

    expect(await refreshStaleStubs(hooksDir, "pre-commit")).toEqual([]);
  });
});

describe("refreshHooks", () => {
  it("adds missing stubs and keeps foreign hooks", () => {
    using repo = setup();
    const hooksDir = hooksDirOf(repo);
    rmSync(join(hooksDir, "post-merge"));
    writeFileSync(join(hooksDir, "pre-push"), "#!/bin/sh\nnpx lint\n");
    writeFileSync(join(hooksDir, "pre-push.pre-ward"), "#!/bin/sh\n");

    const written = refreshHooks(hooksDir, { bin: "dist/cli.mjs" });

    expect(written).toEqual(HOOKS.filter((hook) => hook !== "pre-push"));
    expect(read(hooksDir, "post-merge")).toBe(
      renderStub("post-merge", { bin: "dist/cli.mjs" }),
    );
    expect(read(hooksDir, "pre-push")).toBe("#!/bin/sh\nnpx lint\n");
    expect(read(hooksDir, "pre-push.pre-ward")).toBe("#!/bin/sh\n");
  });

  it("leaves current stubs as they are", () => {
    using repo = createTempRepo();
    const hooksDir = join(repo.dir, ".git", "hooks");
    installHooks(hooksDir);

    expect(refreshHooks(hooksDir, {})).toEqual([]);
  });

  posixOnly("makes the stubs executable", () => {
    using repo = setup();
    const hooksDir = hooksDirOf(repo);
    for (const hook of HOOKS) chmodSync(join(hooksDir, hook), 0o644);

    refreshHooks(hooksDir, {});

    expect(statSync(join(hooksDir, "pre-commit")).mode & 0o111).toBe(0o111);
  });

  it("skips a stub it can't write and goes on", () => {
    using repo = setup();
    const hooksDir = hooksDirOf(repo);
    // The temp file stubs are written through can't be created.
    mkdirSync(join(hooksDir, "pre-commit.ward-tmp", "x"), { recursive: true });

    const written = refreshHooks(hooksDir, {});

    expect(written).toEqual(HOOKS.filter((hook) => hook !== "pre-commit"));
    expect(read(hooksDir, "pre-commit")).toBe(
      v1Stub("pre-commit", "dist/cli.mjs"),
    );
  });
});
